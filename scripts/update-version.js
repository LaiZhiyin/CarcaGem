#!/usr/bin/env node

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const packageJson = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
const version = packageJson.version;
const now = new Date();
const pad = value => String(value).padStart(2, '0');
const versionDate = `${String(now.getFullYear()).slice(-2)}${pad(now.getMonth() + 1)}${pad(now.getDate())}${pad(now.getHours())}${pad(now.getMinutes())}${pad(now.getSeconds())}`;
const buildTime = now.toISOString();
const buildDate = `${now.getFullYear()}/${now.getMonth() + 1}/${now.getDate()} ${pad(now.getHours())}:${pad(now.getMinutes())}:${pad(now.getSeconds())}`;

const versionFile = `// Generated by scripts/update-version.js. Do not edit manually.\nexport const VERSION = '${version}';\nexport const BUILD_DATE_ID = '${versionDate}';\nexport const BUILD_TIME = '${buildTime}';\nexport const BUILD_DATE = '${buildDate}';\nexport const BUILD_DATE_SHORT = BUILD_DATE_ID;\n`;
fs.writeFileSync(path.join(root, 'src/version.ts'), versionFile);

const cacheVersionPattern = /([?&]v=)\d+\.\d+\.\d+/g;
const htmlFiles = ['index.html', 'public/player-guide.html', 'public/admin-dashboard.html'];
for (const relativePath of htmlFiles) {
  const fullPath = path.join(root, relativePath);
  let source = fs.readFileSync(fullPath, 'utf8');
  source = source.replace(/(<meta name="carcagem-version" content=")[^"]*("\s*\/?>)/g, `$1${version}$2`);
  source = source.replace(cacheVersionPattern, `$1${version}`);
  fs.writeFileSync(fullPath, source);
}

for (const directory of ['src', 'public']) {
  const pending = [path.join(root, directory)];
  while (pending.length) {
    const current = pending.pop();
    for (const entry of fs.readdirSync(current, { withFileTypes: true })) {
      const fullPath = path.join(current, entry.name);
      if (entry.isDirectory()) pending.push(fullPath);
      else if (/\.(?:tsx?|jsx?|css)$/.test(entry.name)) {
        const source = fs.readFileSync(fullPath, 'utf8');
        const updated = source.replace(cacheVersionPattern, `$1${version}`);
        if (updated !== source) fs.writeFileSync(fullPath, updated);
      }
    }
  }
}

console.log(`Synchronized CarcaGem version v${version} across the app and public pages.`);
